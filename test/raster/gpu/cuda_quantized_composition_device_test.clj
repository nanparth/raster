(defn activation [case-index]
  (float-array
   (for [row (range 2) col (range 640)
         :let [block (quot col 256) lane (rem col 256)
               scale (/ (+ 1 row block) 4.0)
               code (- (mod (+ (* col 17) (* row 31) (* case-index 43)) 253) 126)
               v (+ (* code scale) (if (= 2 (mod lane 7)) (/ scale 2.0) 0.0))]]
     (cond (and (= 2 case-index) (zero? row)) 0.0
           (zero? lane) (* 127 scale)
           (= 1 lane) (* -127 scale)
           :else v))))

