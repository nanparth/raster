(defn run-resident-cases! [data cases]
  (let [{:keys [quant prepared]} (lower-composition data)
        program (compiled/instantiate! prepared)
        resident (:executable program) nodes (connected-nodes quant prepared)
        last-output (atom nil)]
    (try
      (let [info (compiled/execution-info program)
            descriptions (filter #(and (map? %) (contains? % :entry-points)) (tree-seq coll? seq info))]
        (println "[CUDA Q8_K COMPOSITION BOUND]" info)
        (is (= (set (map :id (:instances (compiled/plan prepared)))) (set (map :instance info))))
        (is (= (phase-coverage prepared) (frequencies (map :instance info))))
        (is (= (reduce + (vals (phase-coverage prepared))) (count descriptions)))
        (is (some #(some (fn [entry] (= "rstr_product_consumer_0" (str entry))) (:entry-points %)) descriptions)))
      (doseq [[input expected] cases]
        ;; Poison shared leaves before replay; only x is admitted as a replay upload.
        (doseq [[key poison] [[:xp (int-array (repeat 384 0x55555555))]
                              [:xs (float-array (repeat 6 Float/NaN))]
                              [:bsums (int-array (repeat 48 Integer/MIN_VALUE))]]]
          (link/upload! resident (get nodes key) poison))
        (let [uploads (atom []) upload-range! gpu/upload-range! previous @last-output
              result (with-redefs [gpu/upload-range!
                                  (fn [session destination source options]
                                    (swap! uploads conj destination)
                                    (upload-range! session destination source options))]
                       (program {[:quant :x] input}))
              output (:y result) actual (value/->host output)]
          (reset! last-output output)
          (when previous (is (not (value/live? previous))))
          (doseq [key [:xp :xs :bsums]]
            (is (not-any? #(= (link/node-view resident (get nodes key)) %) @uploads))
            (let [actual-leaf (link/download resident (get nodes key))]
              (is (= (count (get expected key)) (alength actual-leaf)))
              (is (= (if (= key :xs) (bits (get expected key)) (get expected key))
                     (if (= key :xs) (bits actual-leaf) (vec actual-leaf))))))
          (is (= 17 (alength actual)))
          (is (= (bits (repeat 3 -4096.0)) (bits (drop 14 actual))))
          (if (:compatibility? expected)
            (doseq [[a b] (map vector (take 14 actual) (:y expected))]
              (is (< (Math/abs (- (double a) (double b))) 1e-3)))
            (is (= (bits (:y expected)) (bits (take 14 actual)))))
          (println "[CUDA Q8_K COMPOSITION COMPLETED]"
                   {:returned-elements (alength actual) :logical-elements 14
                    :first-output (aget actual 0) :compatibility? (boolean (:compatibility? expected))})))
      (finally (compiled/close! program)))
    (is (not (value/live? @last-output)))
    (is (zero? (root/lease-count runtime/state)))))

